function isOnDisplay(recipe){
    let displayHtml = document.querySelector("#display-container").innerHTML;
    let recipeDisplay = displayTemplate(recipe);

    return displayHtml.includes(recipeDisplay);
}

function getTime(time){
    let minutes = 0;
    if (typeof time.minute === "number"){
        minutes = time.minute;
    } else {
        minutes = 0;
    }
    if (typeof time.hour === "number"){
        minutes += (time.hour * 60);
    }

    return minutes;
}

function randomOrder(event){
	event.preventDefault();

    let recipeDisplays = document.querySelector("#display-container");

    let currentOrder = Array.from(recipeDisplays.children);

    recipeDisplays = currentOrder.sort(() => Math.random() - 0.5);

    displayContainer.innerHTML = "";

    recipeDisplays.forEach(recipe => {
        displayContainer.appendChild(recipe);
    })
    
    let selectables = document.querySelectorAll(".selectable");
    selectables.forEach(selectable => {
        selectable.addEventListener("click", openSelection);
    });
}

function reverseOrder(event){
	event.preventDefault();

    let recipeDisplays = document.querySelector("#display-container");

    let currentOrder = Array.from(recipeDisplays.children);

    recipeDisplays = currentOrder.reverse();

    displayContainer.innerHTML = "";

    recipeDisplays.forEach(recipe => {
        displayContainer.appendChild(recipe);
    })

    let selectables = document.querySelectorAll(".selectable");
    selectables.forEach(selectable => {
        selectable.addEventListener("click", openSelection);
    });
}

function timeOrder(event){
	event.preventDefault();

    let filterRecipes = recipes.filter(function(recipe){
        return isOnDisplay(recipe);
    })

    let sortedRecipes = filterRecipes.sort(compareRecipes);

    function compareRecipes(a, b) {
        if (getTime(a.times["time1"]) < getTime(b.times["time1"])) {
            return -1;
        } else if (getTime(a.times["time1"]) > getTime(b.times["time1"])) {
            return 1;
        }
        return 0;
    }

    displayContainer.innerHTML = "";

    sortedRecipes.forEach(function(recipe){
        renderDisplay(recipe);
    })
    
    let selectables = document.querySelectorAll(".selectable");
    selectables.forEach(selectable => {
        selectable.addEventListener("click", openSelection);
    });
}

function alphabeticalOrder(event){
	event.preventDefault();

    let filterRecipes = recipes.filter(function(recipe){
        return isOnDisplay(recipe);
    })

    let sortedRecipes = filterRecipes.sort(compareRecipes);

    function compareRecipes(a,b) {
        if (a.name < b.name) {
            return -1;
        } else if (a.name > b.name) {
            return 1;
        }
        return 0;
    }

    displayContainer.innerHTML = "";

    sortedRecipes.forEach(function(recipe){
        renderDisplay(recipe);
    })
    
    let selectables = document.querySelectorAll(".selectable");
    selectables.forEach(selectable => {
        selectable.addEventListener("click", openSelection);
    });
}

function search(event){
	event.preventDefault();

    let recipeQuery = document.querySelector("#search").value;

    let filterRecipes = recipes.filter(function(recipe){
        return (
            recipe.name.toLowerCase().includes(recipeQuery.toLowerCase())
        );
    })

    let sortedRecipes = filterRecipes;

    displayContainer.innerHTML = "";

    sortedRecipes.forEach(function(recipe){
        renderDisplay(recipe);
    })
    
    let selectables = document.querySelectorAll(".selectable");
    selectables.forEach(selectable => {
        selectable.addEventListener("click", openSelection);
    });
}

